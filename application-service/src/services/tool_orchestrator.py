"""
Tool orchestrator - prompt-driven ReAct multi-round tool calling.

For weak models, a ReAct-style system prompt lets the model decide on tool calls
autonomously; rounds repeat until the model produces a final answer, and the full
tool-call process is injected into the system_prompt.
"""
import logging

import asyncio
import inspect
import json
import re
from contextlib import nullcontext
from typing import Any, Dict, List, Optional, Tuple

from ..memory.retrieval_trace.stage_events import (
    is_memory_stage_capture_enabled,
    memory_stage_collector,
)

from ..schemas.model_schema import ModelInfo

logger = logging.getLogger(__name__)

# Tools with a call cap: retrying with a new keyword/parameter is allowed, an
# unbounded retry loop is not.
_TOOL_CALL_LIMITS: Dict[str, int] = {
    "knowledge_retrieval_tool": 3,
    "long_term_memory": 3,
}


def _get_tool_call_limit(name: str) -> Optional[int]:
    """Return the tool's max call count; tools without an entry are uncapped."""
    return _TOOL_CALL_LIMITS.get(name)


# Parse the Thought/Action/Input triple from model output
_ACTION_PATTERN = re.compile(
    r"Thought[：:]\s*(.*?)\s*Action[：:]\s*(\S+)\s*Input[：:]\s*([\s\S]*?\{[\s\S]*?\})",
    re.DOTALL,
)

_REACT_SYSTEM_TEMPLATE = """\
你是具备工具调用能力的智能助手，可根据用户问题自主判断是否使用工具、选择哪个工具、分多轮完成复杂任务。

# 可用工具列表
{all_tools_info}

# 核心原则：历史信息复用优先
在决定调用工具前，**必须先检查历史对话中是否已有相关信息**：
1. 查看历史中的 Observation 字段，那里包含之前工具调用的完整结果
2. 只有当历史信息不足或与当前问题无关时，才考虑调用新工具

# 规划要求
1. 简单、单步、凭常识即可回答的问题，不要规划，直接给最终答案。
2. 只要任务需要多个步骤、多个工具或多来源信息，**必须先规划再动手**：在第一轮输出三段式之前，
先按下面格式给出简短计划，紧接着在同一条回复中继续输出第一轮的 Thought/Action/Input（计划与第一个工具调用在同一轮，不要停下等待确认）：
Plan：
1. 子任务一（预期得到什么结果）
2. 子任务二（预期得到什么结果）
……
Thought：……
Action：……
Input：……
3. 从第二轮起，每轮在 Thought 开头标注当前在执行第几步（如「Thought：执行第2步，……」），严格按计划逐步推进；
可以根据上一轮 Observation 的新情况增删或修订计划步骤，但不得跳过尚未完成的步骤直接给最终答案。

# 基础规则
1. 只能从上面列出的工具中选择，严禁编造不存在的工具名称。
2. 每一轮思考**只能调用一个工具**，不允许一轮同时列出多个工具。
3. 若任务需要多个步骤、依赖多个工具（如先查时间再查天气），必须分多轮依次调用。
4. **禁止用相同参数重复调用同一工具获取相同信息**；但首轮结果为空、不相关或信息不全时，应当换关键词、换角度或调整参数再次调用同一工具（属于不同的有效尝试），或换用其他工具补充，不要只试一次就放弃。
5. 如果用户问题不需要任何工具就能回答（或历史中已有答案），直接给出最终答案，不输出工具调用格式。
6. 工具参数缺失时，不要编造参数，正常推理是否需要继续调用。
7. 复杂或多要点问题不要只调查一个方面就收尾：先在内部把问题拆成若干要点，分多轮把各要点所需的信息查全，再统一作答。

# 输出规范
## 调用工具时，**必须严格使用以下固定三段式格式输出**，一字不差遵守排版：
Thought：你的思考过程，分析用户需求、是否需要调用工具、应该选哪个工具、缺少什么信息
Action：选中的工具名称（必须和工具列表里的名称完全一致）
Input：JSON格式工具入参，无参数则填空对象 {{}}

## 无需调用工具、信息充足可以直接回答用户时：
**直接输出纯自然语言回答即可，严禁输出 Thought、Action、Input 任何字段，不使用任何固定格式**。

# 终止条件（必须同时满足才允许结束工具调用）
1. Plan 中的每个步骤都已执行并有对应 Observation 支撑，用户问题的每个要点也都有 Observation 或历史信息支撑；
2. 没有任何步骤/要点的证据为空、不相关或互相矛盾——若有，必须先换关键词/参数重试或换工具补充，再考虑结束；
3. 上述条件均满足后，整理信息用普通自然语言回复用户，彻底停止三段式格式输出。
如果尽了合理努力（含换关键词重试）仍查不到某个步骤/要点的信息，可以结束，但必须在回答中明确指出该项缺少信息，不得编造。

# 上下文说明
你能看到历史对话和上一轮工具返回的观察结果，请基于已有结果继续推理下一步动作。\
"""

# Final-answer-only prompt (used by the final LLM; contains no tool-calling instructions)
_FINAL_ANSWER_SYSTEM_TEMPLATE = """\
你是专业、友好、准确的智能助手。
请严格基于下方提供的【工具调用过程与结果】来回答用户问题。

规则：
1. 只使用工具返回的信息回答，不编造、不脑补、不扩展无关内容
2. 回答语言自然、通顺、礼貌，符合正常对话风格
3. 如果工具返回结果为空或失败，请如实告知用户
4. 若用户问题中只有部分要点有工具结果支撑，先回答有依据的部分，并明确指出其余要点缺少信息，不得用推测补齐
5. 不要输出任何 Thought/Action/Input 格式内容，只输出自然语言回答
"""


def _build_tools_info(tools: Dict[str, Any]) -> str:
    """Format the tool list into tool descriptions for the prompt."""
    lines = []
    for name, tool in tools.items():
        desc = getattr(tool, "description", "") or ""
        limit = _get_tool_call_limit(name)
        if limit:
            desc = f"[{desc}][最多调用{limit}次：结果不理想时应换关键词/参数重试，不要用相同参数重复调用]"

        param_parts = []

        # 1. Prefer tool_instance.parameters (MCP/Custom tools)
        tool_instance = getattr(tool, "tool_instance", None)
        if tool_instance and hasattr(tool_instance, "parameters"):
            params = tool_instance.parameters
            for p in params:
                # Filter out the operation param (already specified via the tool-name suffix)
                if p.name == "operation":
                    continue
                type_name = p.type.value if hasattr(p.type, "value") else str(p.type)
                part = f"{p.name}({type_name}"
                if p.description:
                    part += f", 说明: {p.description}"
                if p.default is not None:
                    part += f", 默认: {p.default}"
                if p.enum:
                    part += f", 可选值: {p.enum}"
                part += ")"
                param_parts.append(part)

        # 2. Fall back to args_schema (tools generated by the @tool decorator)
        elif hasattr(tool, "args_schema") and tool.args_schema:
            try:
                from pydantic_core import PydanticUndefined
                fields = tool.args_schema.model_fields
                for k, v in fields.items():
                    type_name = v.annotation.__name__ if hasattr(v.annotation, '__name__') else str(v.annotation)
                    part = f"{k}({type_name}"
                    if v.description:
                        part += f", 说明: {v.description}"
                    if v.default is not None and v.default is not PydanticUndefined:
                        part += f", 默认: {v.default}"
                    part += ")"
                    param_parts.append(part)
            except Exception:
                pass

        if param_parts:
            lines.append(f"- {name}[{', '.join(param_parts)}]: {desc}")
        else:
            lines.append(f"- {name}: {desc}")

    return "\n".join(lines)


def _parse_action(text: str, valid_tools: set = None) -> Optional[Tuple[str, str, dict]]:
    """Parse Thought/Action/Input from model output; returns (thought, action, input_dict) or None."""
    m = _ACTION_PATTERN.search(text)
    if not m:
        return None
    thought = m.group(1).strip()
    action = m.group(2).strip()
    input_str = m.group(3).strip()
    # The action must exist in the tool list; otherwise treat it as a final
    # answer (e.g. "none", "no tool needed")
    if valid_tools is not None and action not in valid_tools:
        return None
    try:
        brace_start = input_str.index("{")
        input_dict = json.loads(input_str[brace_start:])
    except (ValueError, json.JSONDecodeError):
        input_dict = {}
    return thought, action, input_dict


class ToolOrchestrator:
    """
    Prompt-driven ReAct multi-round tool-calling orchestrator.

    A ReAct-style system prompt lets weak models decide on tool calls autonomously;
    rounds repeat until the model outputs a final answer, and the full tool-call
    trajectory is returned for injection into the system_prompt.

    Use cases:
    - The model does not support function calling (no 'function_call' capability)
    - Tool calling should depend less on model capability
    """

    def __init__(self, tools: list, max_rounds: int = 5):
        """
        Args:
            tools: list of LangChain tools
            max_rounds: maximum tool-call rounds, prevents infinite loops
        """
        self.tools: Dict[str, Any] = {t.name: t for t in tools}
        self.max_rounds = max_rounds
        self._tool_call_counts: Dict[str, int] = {}
        from .context_assembler import ContextEvidenceCollector
        self.context_collector = ContextEvidenceCollector()
        self.context_assembler = None
        self.context_query = ""
        self.context_base_text = ""

    @classmethod
    async def create_and_run(
        cls,
        tools: list,
        system_prompt: str,
        message: str,
        history: List[Dict],
        model_view: ModelInfo,
        effective_params: Dict[str, Any],
        processed_files: Optional[List[Dict]] = None,
        context_evidence: Optional[List[Any]] = None,
        context_evidence_loader: Optional[Any] = None,
        max_rounds: int = 10,
    ) -> Tuple[str, List[Dict]]:
        """
        Create the orchestrator and run the ReAct loop.

        Returns:
            (updated_system_prompt, node_executions):
            - updated_system_prompt: system_prompt including the tool-call results
            - node_executions: list of tool-call step records
        """
        from ..model_clients import RedBearChatModel

        orchestrator = cls(tools, max_rounds=max_rounds)
        orchestrator.context_collector.add(context_evidence or [])
        orchestrator.context_evidence_loader = context_evidence_loader
        orchestrator.context_evidence_loaded = False
        react_system_prompt = orchestrator.build_react_system_prompt(system_prompt)

        _react_llm = RedBearChatModel.for_invoke(
            model_view,
            params={
                "temperature": effective_params.get("temperature", 0.7),
                "deep_thinking": effective_params.get("deep_thinking", False),
                "thinking_budget_tokens": effective_params.get("thinking_budget_tokens"),
            },
        )

        from .context_assembler import (
            ContextAssembler,
            create_evidence_compressor,
            resolve_evidence_max_tokens,
        )
        orchestrator.context_assembler = ContextAssembler(
            resolve_evidence_max_tokens(effective_params.get("max_tokens") or 2000),
            compressor=create_evidence_compressor(_react_llm),
        )
        orchestrator.context_query = message
        # Evidence budgeting is independent from prompt/history/output tokens.
        orchestrator.context_base_text = react_system_prompt

        async def _llm_caller(msgs):
            full_msgs = [{"role": "system", "content": react_system_prompt}] + msgs
            resp = await _react_llm.ainvoke(full_msgs)
            content = resp.content if hasattr(resp, "content") else str(resp)
            if isinstance(content, list):
                content = "".join(
                    item.get("text", "") if isinstance(item, dict) else str(item)
                    for item in content
                )
            return content.strip()

        react_message = (
            [{"type": "text", "text": message}] + processed_files
            if processed_files else message
        )

        final_answer, trajectory_context, node_executions = await orchestrator.run(
            llm_caller=_llm_caller,
            message=react_message,
            history=history
        )
        logger.info("ReAct 工具调用完成", extra={"final_answer_len": len(final_answer)})

        updated_system_prompt = (
            system_prompt + f"\n\n{_FINAL_ANSWER_SYSTEM_TEMPLATE}"
            + trajectory_context
            + f"\n\n工具调用已完成，调用结果：{final_answer}"
        )
        return updated_system_prompt, node_executions

    def build_react_system_prompt(self, original_system_prompt: str) -> str:
        """
        Merge the original system_prompt with the ReAct tool-calling instructions.
        The ReAct instructions are appended after the original prompt.
        """
        tools_info = _build_tools_info(self.tools)
        react_block = _REACT_SYSTEM_TEMPLATE.format(all_tools_info=tools_info)
        if original_system_prompt:
            return f"{original_system_prompt}\n\n{react_block}"
        return react_block

    async def _call_sync_tool(self, tool: Any, input_dict: dict) -> Any:
        """Run legacy synchronous tools without blocking the event loop."""
        return await asyncio.to_thread(tool.func, **input_dict)

    async def _call_tool(self, name: str, input_dict: dict) -> dict:
        """Execute a single tool call."""
        # Capped tools: past the limit the model is told to switch tools or answer,
        # so an invalid retry loop does not burn rounds.
        limit = _get_tool_call_limit(name)
        if limit is not None:
            self._tool_call_counts[name] = self._tool_call_counts.get(name, 0) + 1
            if self._tool_call_counts[name] > limit:
                return {"success": False, "output": "", "error": f"[{name}] 已调用 {limit} 次，达到上限。请换用其他工具补充信息，或基于已有结果直接回答；不要再次调用本工具。"}
        tool = self.tools.get(name)
        if not tool:
            return {"success": False, "output": "", "error": f"工具 '{name}' 不存在"}
        try:
            if getattr(tool, "coroutine", None):
                result = await tool.ainvoke(input_dict)
            # LangchainToolWrapper uses _arun; @tool-decorated tools use func
            elif hasattr(tool, 'func') and callable(tool.func):
                result = await self._call_sync_tool(tool, input_dict)
            else:
                # LangchainToolWrapper: the tool name may carry an operation suffix
                # (e.g. datetime_tool_now); extract the operation and inject it as a param
                tool_instance = getattr(tool, 'tool_instance', None)
                if tool_instance and not input_dict.get('operation') and hasattr(tool_instance, 'operation'):
                    operation = getattr(tool_instance, 'operation', '')
                    input_dict = {**input_dict, 'operation': operation}
                result = await tool._arun(**input_dict)
            logger.debug(f"工具 '{name}' 执行成功，结果长度={len(str(result))}")
            return {"success": True, "output": str(result), "error": None}
        except Exception as e:
            logger.warning(f"工具 '{name}' 执行失败: {e}")
            return {"success": False, "output": "", "error": f"[工具调用失败: {e}]"}

    async def run(self, llm_caller, message: str | list, history: List[Dict]) -> Tuple[str, str, List[Dict]]:
        """
        Run the ReAct multi-round tool-calling loop.

        Args:
            llm_caller: async function with signature async (messages: list) -> str
                that calls the underlying LLM
            message: current user message, string or multimodal content list
            history: conversation history list

        Returns:
            (final_answer, trajectory_context, node_executions):
            - final_answer: the model's final natural-language answer
            - trajectory_context: full tool-call trajectory, for injection into the system_prompt
            - node_executions: list of tool-call step records (for agent_executions)
        """
        import time
        import uuid as _uuid

        # Build the initial message list (history + current user message;
        # multimodal content supported)
        messages = list(history) + [{"role": "user", "content": message}]

        trajectory: List[str] = []  # records each round's thought/action/observation
        node_executions: List[Dict] = []  # tool-call step records
        final_answer = ""
        response = ""

        for round_idx in range(self.max_rounds):
            response = await llm_caller(messages)

            parsed = _parse_action(response, valid_tools=set(self.tools.keys()))

            if parsed is None:
                # Strip any residual Thought/Action/Input block, keep the natural
                # language that follows
                clean = re.sub(
                    r"Thought[：:][\s\S]*?Input[：:]\s*\{[^{}]*}\s*",
                    "",
                    response,
                ).strip()
                final_answer = clean or response.strip()
                logger.info(f"ReAct 第 {round_idx + 1} 轮：模型给出最终答案")
                if not self.context_collector.snapshot():
                    logger.info(
                        "[上下文组装] 未触发 | "
                        "原因=ReAct 未调用知识库或长期记忆工具，因此没有外部证据可组装"
                    )
                break

            thought, action, input_dict = parsed
            logger.info(f"ReAct 第 {round_idx + 1} 轮：调用工具 '{action}'，参数={input_dict}")

            # Record tool-call start
            step_start = time.time()
            step_id = str(_uuid.uuid4())

            # Execute the tool
            collector = (
                memory_stage_collector()
                if is_memory_stage_capture_enabled() and action == "long_term_memory"
                else nullcontext([])
            )
            with collector as memory_stages:
                tool_result = await self._call_tool(action, input_dict)

            success: bool = bool(tool_result.get("success", True))
            output: str = str(tool_result.get("output") or "")
            error: Optional[str] = tool_result.get("error")

            observation = f"[错误: {error}]" if error else output
            tool = self.tools.get(action)
            evidence = getattr(tool, "_context_evidence", None) if tool else None
            if success and tool and not evidence:
                from .context_assembler import context_evidence_from_tool_result
                evidence = context_evidence_from_tool_result(tool, output, input_dict)
            context_stats = None
            if success and evidence and self.context_assembler:
                self.context_collector.add(evidence)
                if not getattr(self, "context_evidence_loaded", False) and getattr(self, "context_evidence_loader", None):
                    extra = self.context_evidence_loader()
                    if inspect.isawaitable(extra):
                        extra = await extra
                    self.context_collector.add(extra or [])
                    self.context_evidence_loaded = True
                tool._context_evidence = []
                assembled = await self.context_assembler.assemble(
                    self.context_collector.snapshot(), query=self.context_query,
                    base_text=(
                        self.context_base_text + "\n" +
                        json.dumps(messages, ensure_ascii=False, default=str) + "\n" +
                        response
                    ),
                    message_count=len(messages) + 1,
                    triggered_by=[action],
                )
                if assembled.context_text:
                    observation = assembled.context_text
                else:
                    observation = "[外部上下文未注入：组装后为空，避免回退发送原始大段工具结果]"
                    logger.warning(
                        "[上下文组装] 未注入原始工具正文 | 原因=组装结果为空，已阻止大段工具结果回退"
                    )
                context_stats = {
                    "triggered_by": assembled.triggered_by,
                    "evidence_count": len(assembled.evidence),
                    "compressed_count": len(assembled.compressed_evidence_keys),
                    "dropped_count": len(assembled.dropped_evidence),
                    "estimated_tokens": assembled.estimated_tokens,
                }

            # Build the step record
            tool = self.tools.get(action)
            tool_meta = getattr(tool, "_tool_meta", None) if tool else None
            elapsed_ms = round((time.time() - step_start) * 1000, 2)

            node = {
                "step_id": step_id,
                "node_type": "tool",
                "node_name": action,
                "status": "completed" if success else "failed",
                "input": json.dumps(input_dict, ensure_ascii=False)[:2000],
                "output": output[:2000],
                "elapsed_time": elapsed_ms,
                "error": error,
                "meta": tool_meta if tool_meta else None,
            }
            if memory_stages:
                # Request-local transport data.  AppChatService replays it and
                # removes this key before agent-execution persistence.
                node["_memory_stages"] = list(memory_stages)
            # Extract knowledge-base sources
            if tool and hasattr(tool, "_last_sources") and tool._last_sources:
                if not node["meta"]:
                    node["meta"] = {}
                node["meta"]["sources"] = tool._last_sources
                tool._last_sources = []
            if context_stats:
                if not node["meta"]:
                    node["meta"] = {}
                node["meta"]["context_assembly"] = context_stats
            node_executions.append(node)

            # Record this round's trajectory
            trajectory.append(
                f"Thought：{thought}\n"
                f"Action：{action}\n"
                f"Input：{json.dumps(input_dict, ensure_ascii=False)}\n"
                f"Observation：{observation}"
            )

            # Merge this round's ReAct trajectory into one assistant message for
            # the next round of reasoning
            messages.append({"role": "assistant", "content": f"{response}\nObservation：{observation}"})

        else:
            # Max rounds reached; force the last model output as the answer
            logger.warning(f"ReAct 达到最大轮数 {self.max_rounds}，强制终止")
            final_answer = response.strip() if response else "已达到最大思考轮次，无法继续"

        trajectory_context = self.build_trajectory_context(trajectory)
        return final_answer, trajectory_context, node_executions

    @staticmethod
    def build_trajectory_context(trajectory: List[str]) -> str:
        """Format the tool-call trajectory into a context block for the system_prompt."""
        if not trajectory:
            return ""
        parts = ["\n\n---\n以下是工具调用过程与结果，请基于这些信息给出最终回答："]
        parts.extend(trajectory)
        parts.append("---")
        return "\n\n".join(parts)
