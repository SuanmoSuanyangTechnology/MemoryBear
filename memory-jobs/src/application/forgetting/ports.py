"""Dependencies used by this context, implemented by infrastructure."""

from typing import Protocol


class ForgettingRepository(Protocol):
    def record_pair(self, context: dict, pair: dict, job_id: str, when: str) -> None: ...
    def finish_forgetting(
        self, context: dict, report: dict, pairs: list[dict], job_id: str
    ) -> None: ...


class ForgettingSource(Protocol):
    def knowledge_count(self, user_id: str) -> int: ...
    def active_count(self, user_id: str) -> int: ...
    def forgetting_pairs(
        self, user_id: str, threshold: float, days: int, limit: int
    ) -> list[dict]: ...
    def merge_pair(self, context: dict, pair: dict, summary: dict, job_id: str) -> bool: ...
    def activation_stats(self, user_id: str, threshold: float) -> dict: ...
